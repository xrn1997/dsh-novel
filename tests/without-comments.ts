/**
 * 注释剥除（守卫扫描「代码里」用）：块注释换空格、行注释抹到行尾（`//` 前留非 `:` 断言，别截断
 * `https://`）。刻意**不**去字符串字面量：本仓的证据有一大半正当住在串里（宿主方法名、沙箱模板串、
 * 规则字段白名单），按串再筛会把真实现判成假账（实测误伤 8 行）；剩下的缺口只有「告警文案里提到
 * 某符号」，那不构成实现声明。
 * 此前有三份逐字抄本互相指认「同一手法」，改一处只能靠人记得同改，故收成这一份。
 */
export function withoutComments(text: string): string {
  return text
    .replace(/\/\*[\s\S]*?\*\//g, ' ')
    .replace(/(?<!:)\/\/[^\n]*/g, '')
}
